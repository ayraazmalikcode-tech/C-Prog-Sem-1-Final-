#include <stdio.h>

int main() {
    printf("\n\t*** STUDENT DETAILS ***\n");
    printf("\t\t------------------------\n\n");
    printf("Name\t\t: Rahul Sharma\n");
    printf("Age\t\t: 18 years\n");
    printf("Class\t\t: FE (Sem 1)\n");
    printf("Division\t: A\n");
    printf("UIN\t\t: 2026010142\n\n");
    printf("Saved in\t: \"C:\\CPL_Lab\\Exp1\"\n");
    printf("Escape sequences used: \\n  \\t \\\" \\\\");
    return 0;
}